// IPC window code removed — replaced by PipeServer (pipe_server.h/cpp)

void InitD3d(HWND hwnd, int width, int height) {
  HRESULT hr;

  // DX12 debug layer: Debug builds only (forgejo#16). Off in Release --
  // 5-10x perf hit, and DXContext::DrainDebugMessages() (per-frame, gated on
  // whether the device actually returned an ID3D12InfoQueue) is what turns
  // whatever this catches into log/debug.log lines instead of a silent
  // corrupted frame or an unexplained device removal.
  UINT dxgiFactoryFlags = 0;
#ifdef _DEBUG
  {
    ComPtr<ID3D12Debug> debugController;
    if (SUCCEEDED(D3D12GetDebugInterface(IID_PPV_ARGS(&debugController)))) {
      debugController->EnableDebugLayer();
      dxgiFactoryFlags |= DXGI_CREATE_FACTORY_DEBUG;
      mdropdx12.LogInfo(L"InitD3d: DX12 debug layer enabled (Debug build)");
    }
  }
#endif

  // DRED (Device Removed Extended Data). A GPU hang otherwise reports only
  // 0x887A0006 with no indication of WHICH work hung — the whole reason the
  // canvas-realloc-with-mirrors hang resisted diagnosis. Breadcrumbs give the
  // last GPU ops per command list; page-fault data names the resource at the
  // faulting VA and, crucially, whether it was recently FREED — which is what
  // a descriptor/resource aliasing bug looks like from the GPU side.
  // Must be set before the device is created. Costs a little per-op overhead.
  {
    ComPtr<ID3D12DeviceRemovedExtendedDataSettings> dred;
    if (SUCCEEDED(D3D12GetDebugInterface(IID_PPV_ARGS(&dred))) && dred) {
      dred->SetAutoBreadcrumbsEnablement(D3D12_DRED_ENABLEMENT_FORCED_ON);
      dred->SetPageFaultEnablement(D3D12_DRED_ENABLEMENT_FORCED_ON);
      mdropdx12.LogInfo(L"InitD3d: DRED breadcrumbs + page-fault reporting enabled");
    }
  }

  hr = CreateDXGIFactory2(dxgiFactoryFlags, IID_PPV_ARGS(&pDXGIFactory));
  if (FAILED(hr)) {
    mdropdx12.LogInfo(L"InitD3d: CreateDXGIFactory2 failed");
    return;
  }

  // Choose adapter: prefer the one at g_engine.m_adapterId, fall back to first hardware adapter.
  ComPtr<IDXGIAdapter1> hardwareAdapter;
  UINT wantedIdx = g_engine.m_adapterId;
  for (UINT i = 0; ; i++) {
    ComPtr<IDXGIAdapter1> adapter;
    if (pDXGIFactory->EnumAdapters1(i, &adapter) == DXGI_ERROR_NOT_FOUND)
      break;
    DXGI_ADAPTER_DESC1 desc;
    adapter->GetDesc1(&desc);
    if (desc.Flags & DXGI_ADAPTER_FLAG_SOFTWARE)
      continue;
    // Per-adapter result. "adapter=NONE" alone cannot distinguish "DXGI
    // enumerated nothing" from "every adapter refused a device", and those
    // point at completely different causes during TDR recovery (#230).
    const HRESULT hrTest = D3D12CreateDevice(adapter.Get(), D3D_FEATURE_LEVEL_11_0,
                                             _uuidof(ID3D12Device), nullptr);
    if (FAILED(hrTest)) {
      char abuf[192];
      sprintf(abuf, "InitD3d: adapter %u '%ls' rejected hr=0x%08X",
              i, desc.Description, (unsigned)hrTest);
      DebugLogA(abuf, LOG_ERROR);
    }
    if (SUCCEEDED(hrTest)) {
      if (hardwareAdapter == nullptr || i == wantedIdx) {
        hardwareAdapter = adapter;
        if (i == wantedIdx) break;
      }
    }
  }

  hr = D3D12CreateDevice(hardwareAdapter.Get(), D3D_FEATURE_LEVEL_11_0, IID_PPV_ARGS(&pD3DDevice));
  if (FAILED(hr)) {
    // The HRESULT, and whether an adapter was even found. Without these the
    // TDR-recovery failure reads as "D3D12CreateDevice failed" six times over
    // and says nothing about why -- which is exactly where #230's recovery
    // attempt stalled. It fails INSTANTLY after a TDR, so it is not the
    // driver-still-resetting case the retry loop was built for.
    char buf[192];
    sprintf(buf, "InitD3d: D3D12CreateDevice failed hr=0x%08X adapter=%s "
                 "(wanted idx %u)",
            (unsigned)hr, hardwareAdapter ? "found" : "NONE",
            (unsigned)wantedIdx);
    DebugLogA(buf, LOG_ERROR);
    return;
  }

  // Keep IDXGIAdapter3 for VRAM budget queries (QueryVideoMemoryInfo)
  g_pDxgiAdapter.Reset();
  if (hardwareAdapter) {
    hardwareAdapter.As(&g_pDxgiAdapter);
    if (!g_pDxgiAdapter)
      mdropdx12.LogInfo(L"InitD3d: IDXGIAdapter3 unavailable — VRAM budget monitoring disabled");
  }

  D3D12_COMMAND_QUEUE_DESC queueDesc = {};
  queueDesc.Flags = D3D12_COMMAND_QUEUE_FLAG_NONE;
  queueDesc.Type  = D3D12_COMMAND_LIST_TYPE_DIRECT;
  hr = pD3DDevice->CreateCommandQueue(&queueDesc, IID_PPV_ARGS(&pCommandQueue));
  if (FAILED(hr)) {
    mdropdx12.LogInfo(L"InitD3d: CreateCommandQueue failed");
    return;
  }

  // Set back-buffer dimensions before PluginInitialize creates the swap chain.
  if (!g_engine.IsSpoutActiveAndFixed()) {
    g_engine.SetVariableBackBuffer(width, height);
  }
}

void DeinitD3d() {
  // ComPtrs release automatically; flush any in-flight GPU work first via the
  // plugin's DXContext, which calls WaitForGpu() in its destructor / PluginQuit().
  g_pDxgiAdapter.Reset();
  pCommandQueue.Reset();
  pD3DDevice.Reset();
  pDXGIFactory.Reset();
}

// Query local VRAM budget via DXGI. Returns true if a sample was written.
// availablePercent = 100 * (Budget - CurrentUsage) / Budget
static bool QueryLocalVramBudget(UINT64* outBudget, UINT64* outUsage, float* outAvailablePercent) {
  if (!g_pDxgiAdapter || !outBudget || !outUsage || !outAvailablePercent)
    return false;

  DXGI_QUERY_VIDEO_MEMORY_INFO info = {};
  HRESULT hr = g_pDxgiAdapter->QueryVideoMemoryInfo(0, DXGI_MEMORY_SEGMENT_GROUP_LOCAL, &info);
  if (FAILED(hr) || info.Budget == 0)
    return false;

  *outBudget = info.Budget;
  *outUsage = info.CurrentUsage;
  double free = (info.CurrentUsage < info.Budget)
    ? (double)(info.Budget - info.CurrentUsage)
    : 0.0;
  *outAvailablePercent = (float)(100.0 * free / (double)info.Budget);
  return true;
}

// VRAM checkpoints (#344). Lives here because g_pDxgiAdapter does.
//
// ~1.9 GB of LOCAL VRAM is committed the first time mirror rendering is
// switched on, and nothing in the tree allocates anything like that directly:
// the app has 30 CreateCommittedResource sites and none is fixed-size and huge.
// Attributing it meant changing one variable at a time from outside the
// process, because the engine's own sample is two seconds coarse and there was
// no way to ask "what did THIS call cost".
static std::atomic<bool> g_vramMarkOn{false};
static std::atomic<unsigned long long> g_vramMarkPrev{0};

void VramMarkSetEnabled(bool on) {
  g_vramMarkOn.store(on, std::memory_order_release);
  // Re-baseline on every enable, so the first mark of a run reports the level
  // rather than a delta against whenever it was last switched off.
  g_vramMarkPrev.store(0, std::memory_order_release);
}

bool VramMarkEnabled() {
  return g_vramMarkOn.load(std::memory_order_acquire);
}

void VramMark(const char* tag) {
  UINT64 budget = 0, usage = 0;
  float pct = 0.0f;
  if (!QueryLocalVramBudget(&budget, &usage, &pct))
    return;
  const unsigned long long prev = g_vramMarkPrev.exchange(usage);
  char buf[224];
  if (prev == 0)
    sprintf(buf, "VMARK %-40s %9.1f MB\n", tag, usage / 1048576.0);
  else
    sprintf(buf, "VMARK %-40s %9.1f MB  (%+9.1f MB)\n", tag,
            usage / 1048576.0,
            ((double)usage - (double)prev) / 1048576.0);
  DebugLogA(buf, LOG_WARN);
}

// Poll VRAM budget; update engine sample fields; exit cleanly if below threshold.
// Also samples when debug overlay is on so budget/available% are visible live.
static void PollVramBudgetAndMaybeExit(HWND hwnd) {
  if (g_engine.m_bVramExitTriggered)
    return;

  // GPU utilisation, on its own one-second gate. It must NOT ride the VRAM
  // throttle below, which sits after an early return this needs to run past --
  // and it must be throttled, because each Poll() walks every GPU engine
  // instance on the machine and this function is called every frame.
  //
  // Opened lazily and closed again the moment nothing is asking, so an
  // ordinary run pays nothing at all.
  {
    static DWORD s_lastGpuMs = 0;
    const DWORD nowGpu = GetTickCount();
    if (s_lastGpuMs == 0 || (nowGpu - s_lastGpuMs) >= 1000) {
      s_lastGpuMs = nowGpu;
      if (g_engine.GpuUsageWanted())
        g_engine.m_gpuUsage.Poll();
      else
        g_engine.m_gpuUsage.Close();
    }
  }

  // The sample itself is unconditional now. It used to run only when the
  // low-VRAM exit or the debug overlay wanted it, which meant that on a default
  // configuration m_vramBudgetBytes stayed 0 for the whole session -- and the
  // mirror swap-chain cap derives from it (#254), so it would have silently
  // fallen back to the fixed 1920 it exists to replace. One DXGI query every two
  // seconds is not worth gating.
  static DWORD s_lastPollMs = 0;
  static int s_lowSamples = 0;
  DWORD now = GetTickCount();
  if (s_lastPollMs != 0 && (now - s_lastPollMs) < 2000)
    return;
  s_lastPollMs = now;

  UINT64 budget = 0, usage = 0;
  float availablePct = 100.0f;
  if (!QueryLocalVramBudget(&budget, &usage, &availablePct))
    return;

  g_engine.m_vramBudgetBytes = budget;
  g_engine.m_vramUsageBytes = usage;
  g_engine.m_vramAvailablePercent = availablePct;
  // Cheap: returns immediately unless the derived cap actually moved.
  g_engine.RefreshMirrorSwapChainCap();

  if (g_engine.m_nMinAvailableVramPercent <= 0)
    return;

  if (availablePct < (float)g_engine.m_nMinAvailableVramPercent) {
    s_lowSamples++;
    if (s_lowSamples < 2)
      return; // require two consecutive low samples (~4s) to avoid flapping

    g_engine.m_bVramExitTriggered = true;
    g_engine.m_bShowDebugInfo = true; // show budget + available% in debug overlay

    const double budgetMB = (double)budget / (1024.0 * 1024.0);
    const double usageMB = (double)usage / (1024.0 * 1024.0);
    wchar_t msg[256];
    swprintf(msg, 256,
      L"VRAM pressure: available %.1f%% (usage %.0f / budget %.0f MB) — exiting",
      availablePct, usageMB, budgetMB);
    mdropdx12.LogInfo(msg);
    {
      char abuf[256];
      FormatToA(abuf,
        "VRAM pressure EXIT: available=%.1f%% usage=%.0fMB budget=%.0fMB threshold=%d%%",
        availablePct, usageMB, budgetMB, g_engine.m_nMinAvailableVramPercent);
      DebugLogA(abuf, LOG_ERROR);
    }
    g_engine.AddError(msg, 30.0f, ERR_MISC, true);

    if (hwnd)
      PostMessage(hwnd, WM_CLOSE, 0, 0);
  } else {
    s_lowSamples = 0;
  }
}

//Multiple monitor stretch - Credit to @milkdropper for the code!
void ToggleStretch(HWND hwnd) {
  if (!stretch) {
    int width = GetSystemMetrics(SM_CXVIRTUALSCREEN);
    int height = GetSystemMetrics(SM_CYVIRTUALSCREEN);
    int left = GetSystemMetrics(SM_XVIRTUALSCREEN);
    int top = GetSystemMetrics(SM_YVIRTUALSCREEN);

    if (!fullscreen) {
      lastWindowStyle = GetWindowLongPtr(hwnd, GWL_STYLE);
      lastWindowStyleEx = GetWindowLongPtrW(hwnd, GWL_EXSTYLE);
      lastWindowStyleEx &= ~WS_EX_TOPMOST;
      GetWindowRect(hwnd, &lastRect);
      PersistLastRectAsWindowedRestore();
    }

    g_engine.SetVariableBackBuffer(width, height);
    // DX12: swap chain resize is triggered by the WM_SIZE handler after SetWindowPos.
    SetWindowLongPtrW(hwnd, GWL_STYLE, WS_POPUP | WS_VISIBLE);
    SetWindowLongPtrW(hwnd, GWL_EXSTYLE, RenderWindowTaskbarExStyle(g_engine.m_bChildMode));
    SetWindowPos(hwnd, HWND_NOTOPMOST, left, top, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    SetThreadExecutionState(ES_DISPLAY_REQUIRED | ES_CONTINUOUS | ES_SYSTEM_REQUIRED | ES_AWAYMODE_REQUIRED);
    DragAcceptFiles(hwnd, TRUE);

    stretch = true;
    ForegroundUnlessQuietStartup(hwnd);
  }
  else {
    ForceCursorVisible();

    int x = lastRect.left;
    int y = lastRect.top;
    int width = lastRect.right - lastRect.left;
    int height = lastRect.bottom - lastRect.top;

    g_engine.SetVariableBackBuffer(width, height);
    // DX12: swap chain resize is triggered by the WM_SIZE handler after SetWindowPos.
    SetThreadExecutionState(ES_DISPLAY_REQUIRED | ES_SYSTEM_REQUIRED | ES_AWAYMODE_REQUIRED);
    stretch = false;

    SetWindowLongPtrW(hwnd, GWL_STYLE, lastWindowStyle);
    SetWindowLongPtrW(hwnd, GWL_EXSTYLE, lastWindowStyleEx);
    SetWindowPos(hwnd, HWND_NOTOPMOST, lastRect.left, lastRect.top, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    SetWindowPos(hwnd, 0, 0, 0, 0, 0, SWP_DRAWFRAME | SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE | SWP_NOZORDER);
    if (borderless) {
      SetWindowLongPtrW(hwnd, GWL_STYLE, WS_POPUP | WS_VISIBLE);
      SetWindowPos(hwnd, HWND_TOPMOST, x, y, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    }
    ForegroundUnlessQuietStartup(hwnd);
  }
  fullscreen = false;
}

static void ToggleClickThrough(HWND hWnd) {
  try {


    // Retrieve the current alpha value
    BYTE currentAlpha = 255; // Default to fully opaque
    DWORD flags = 0;
    COLORREF colorKey = 0;
    if (GetLayeredWindowAttributes(hWnd, &colorKey, &currentAlpha, &flags)) {
      // Successfully retrieved the current alpha value
    }

    if (clickthrough) {
      // Make the window normal while retaining WS_EX_LAYERED
      LONG_PTR style = GetWindowLongPtr(hWnd, GWL_EXSTYLE);
      style &= ~WS_EX_TRANSPARENT; // Remove click-through
      SetWindowLongPtr(hWnd, GWL_EXSTYLE, style);
      SetLayeredWindowAttributes(hWnd, 0, currentAlpha, LWA_ALPHA);
    }
    else {
      // Make the window click-through
      LONG_PTR style = GetWindowLongPtr(hWnd, GWL_EXSTYLE);
      style |= WS_EX_LAYERED | WS_EX_TRANSPARENT;
      SetWindowLongPtr(hWnd, GWL_EXSTYLE, style);
      SetLayeredWindowAttributes(hWnd, 0, currentAlpha, LWA_ALPHA);
    }
    clickthrough = !clickthrough;
  } catch (const std::exception& e) {
    mdropdx12.LogException(L"ToggleClickThrough", e, true);
  }
}

static void ToggleBorderlessFullscreen(HWND hWnd) {
  try {
    static bool previousClickthrough = false; // Store the previous clickthrough state
    static float previousOpacity = 1.0f; // Store the previous opacity (fully opaque by default)

    // Check if Shift is pressed
    bool isShiftPressed = (GetKeyState(VK_SHIFT) & 0x8000) != 0;

    // Where fullscreen means, for THIS window: the nearest monitor's work area
    // normally, but a child's own display in full. Shared with
    // IsBorderlessFullscreen so the test and the action cannot disagree --
    // when they did, SET_BORDERLESS_FS=1 on a correctly placed child "entered"
    // fullscreen by shrinking it to the work area, 48px short on the monitor
    // holding the taskbar, and pinned it to whichever monitor it was nearest
    // rather than the one it owns (#240).
    {
      RECT workArea = g_engine.FullscreenTargetRect(hWnd);

      // Check if the window is already in borderless fullscreen mode
      RECT currentRect;
      GetWindowRect(hWnd, &currentRect);

      if (currentRect.left == workArea.left &&
        currentRect.top == workArea.top &&
        currentRect.right == workArea.right &&
        currentRect.bottom == workArea.bottom) {
        // window appears to be borderless fullscreen
        // Restore the previous window dimensions, borderless state, clickthrough state, and opacity
        LONG_PTR style = GetWindowLongPtr(hWnd, GWL_STYLE);
        if (g_engine.m_WindowBorderless) {
          style = WS_POPUP | WS_VISIBLE; // Restore borderless style
        }
        else {
          style = WS_OVERLAPPEDWINDOW | WS_VISIBLE; // Restore normal window style
        }
        SetWindowLongPtr(hWnd, GWL_STYLE, style);

        // Check if the saved dimensions are the same as the current dimensions
        if (g_engine.m_WindowWidth == (currentRect.right - currentRect.left) &&
          g_engine.m_WindowHeight == (currentRect.bottom - currentRect.top)) {
          // Reduce the dimensions by 50%
          g_engine.m_WindowWidth /= 2;
          g_engine.m_WindowHeight /= 2;

          // Center the window ON THIS MONITOR.
          //
          // workArea.left/top are the monitor's ORIGIN in virtual-desktop
          // coordinates and have to be added back: the expression in
          // parentheses is an offset within the monitor, not a position.
          // Without them the window is centred on whatever monitor has its
          // origin at (0,0) -- the primary -- from wherever it actually was.
          //
          // Invisible on the primary, because there the origin IS (0,0), which
          // is why this survived. On any other monitor the window jumps.
          // Measured on a child covering DISPLAY1 at (0,-1440)-(2560,0):
          // halved to 1280x720, then placed at ((2560-1280)/2,
          // (1440-720)/2) = (640,360) -- which is the middle of the PRIMARY.
          // Reported as "turn on/off watermark and try to reactivate the
          // screen on display1 ... it moves to display3 as centered windowed
          // screen"; display3 was simply the monitor at the origin.
          g_engine.m_WindowX = workArea.left +
              (workArea.right - workArea.left - g_engine.m_WindowWidth) / 2;
          g_engine.m_WindowY = workArea.top +
              (workArea.bottom - workArea.top - g_engine.m_WindowHeight) / 2;
        }

        SetWindowPos(
          hWnd,
          g_engine.m_WindowBorderless ? HWND_TOPMOST : HWND_NOTOPMOST,
          g_engine.m_WindowX,
          g_engine.m_WindowY,
          g_engine.m_WindowWidth,
          g_engine.m_WindowHeight,
          SWP_FRAMECHANGED | SWP_NOZORDER | SWP_NOACTIVATE
        );

        // Restore the previous clickthrough state
        if (clickthrough != previousClickthrough) {
          ToggleClickThrough(hWnd);
        }

        if (g_engine.fOpacity != previousOpacity) {
          g_engine.fOpacity = previousOpacity;
          g_engine.SetOpacity(hWnd);
        }

        // Restore the previous opacity
        // SetLayeredWindowAttributes(hWnd, 0, previousOpacity, LWA_ALPHA);

        borderless = g_engine.m_WindowBorderless; // Restore the borderless state
        fullscreen = false;
        ForegroundUnlessQuietStartup(hWnd);
      }
      else {
        // not in borderless fullscreen mode, so toggle to it
        // Save the current window dimensions, borderless state, clickthrough state, and opacity
        RECT currentWindowRect;
        GetWindowRect(hWnd, &currentWindowRect);
        g_engine.m_WindowX = currentWindowRect.left;
        g_engine.m_WindowY = currentWindowRect.top;
        g_engine.m_WindowWidth = currentWindowRect.right - currentWindowRect.left;
        g_engine.m_WindowHeight = currentWindowRect.bottom - currentWindowRect.top;
        g_engine.m_WindowBorderless = borderless; // Save the current borderless state

        previousClickthrough = clickthrough; // Save the current clickthrough state
        previousOpacity = g_engine.fOpacity;

        // Set the window style to borderless
        LONG_PTR style = GetWindowLongPtr(hWnd, GWL_STYLE);
        style &= ~(WS_OVERLAPPEDWINDOW); // Remove standard window styles
        style |= WS_POPUP; // Add popup style for borderless
        SetWindowLongPtr(hWnd, GWL_STYLE, style);

        // Set the window position and size to fit the work area
        SetWindowPos(
          hWnd,
          isShiftPressed ? HWND_TOPMOST : HWND_NOTOPMOST,
          workArea.left,
          workArea.top,
          workArea.right - workArea.left,
          workArea.bottom - workArea.top,
          SWP_FRAMECHANGED | SWP_NOACTIVATE
        );

        // If Shift is pressed, enable clickthrough
        if (isShiftPressed) {
          if (!clickthrough) {
            ToggleClickThrough(hWnd);
          }
          g_engine.fOpacity = g_engine.m_WindowWatermarkModeOpacity;
          g_engine.SetOpacity(hWnd);
          //SetLayeredWindowAttributes(hWnd, 0, (BYTE)(g_engine.m_WindowWatermarkModeOpacity * 255), LWA_ALPHA);
        }

        g_engine.m_bAlwaysOnTop = isShiftPressed; // Set always on top based on Shift key state
        borderless = true;
        ForegroundUnlessQuietStartup(hWnd);
      }
    }
  } catch (const std::exception& e) {
    mdropdx12.LogException(L"ToggleBorderlessFullscreen", e, true);
  }
}

static void ToggleFullScreen(HWND hwnd) {
  // Resync sticky flag with geometry in BOTH directions, not just
  // true->false: the flag can go stale false->true too, and that half went
  // unhandled until forgejo#98's testing exposed it. ToggleBorderlessFullscreen
  // (WM_MW_BORDERLESS_FS, what SET_ALL_FULLSCREEN=/the phone remote use) never
  // sets `fullscreen` true on entry -- only clears it on exit, one-directional
  // -- so a window made fullscreen that way still reads `fullscreen==false`
  // here. A bare toggle (SIGNAL|FULLSCREEN's MW_FS_TOGGLE, e.g. a hotkey) on
  // such a window then took the ENTER branch again instead of exiting: no
  // visible change, and it silently re-armed `fullscreen=true` with `lastRect`
  // captured from the ALREADY-fullscreen geometry, poisoning the next real
  // exit's restore target too. Trusting coversMonitor over the sticky flag in
  // both directions is what the pre-existing one-way correction below was
  // already trying to approximate.
  const bool coversMonitor = WindowCoversNearestMonitor(hwnd, false);
  fullscreen = coversMonitor;

  if (fullscreen) {
    // Regular fullscreen → restore to saved position
    ForceCursorVisible();

    int x = lastRect.left;
    int y = lastRect.top;
    int width = lastRect.right - lastRect.left;
    int height = lastRect.bottom - lastRect.top;
    if (width < 160) width = 1280;
    if (height < 120) height = 720;

    g_engine.SetVariableBackBuffer(width, height);
    SetThreadExecutionState(ES_DISPLAY_REQUIRED | ES_SYSTEM_REQUIRED | ES_AWAYMODE_REQUIRED);
    fullscreen = false;

    SetWindowLongPtrW(hwnd, GWL_STYLE, lastWindowStyle ? lastWindowStyle : (WS_OVERLAPPEDWINDOW | WS_VISIBLE));
    SetWindowLongPtrW(hwnd, GWL_EXSTYLE, lastWindowStyleEx);
    SetWindowPos(hwnd, HWND_NOTOPMOST, lastRect.left, lastRect.top, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    SetWindowPos(hwnd, 0, 0, 0, 0, 0, SWP_DRAWFRAME | SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE | SWP_NOZORDER);
    if (borderless) {
      SetWindowLongPtrW(hwnd, GWL_STYLE, WS_POPUP | WS_VISIBLE);
      SetWindowPos(hwnd, HWND_TOPMOST, x, y, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    }
    ForegroundUnlessQuietStartup(hwnd);
  }
  else {
    // Enter true monitor fullscreen.
    // Previously: IsBorderlessFullscreen → ToggleBorderlessFullscreen *exited* work-area
    // FS instead of promoting to full rcMonitor — felt like "fullscreen does nothing".
    if (!stretch) {
      lastWindowStyle = GetWindowLongPtr(hwnd, GWL_STYLE);
      lastWindowStyleEx = GetWindowLongPtrW(hwnd, GWL_EXSTYLE);
      lastWindowStyleEx &= ~WS_EX_TOPMOST;
      GetWindowRect(hwnd, &lastRect);
      PersistLastRectAsWindowedRestore();
    }

    HMONITOR monitor = MonitorFromWindow(hwnd, MONITOR_DEFAULTTONEAREST);

    MONITORINFO info;
    info.cbSize = sizeof(MONITORINFO);

    GetMonitorInfoW(monitor, &info);

    int width = info.rcMonitor.right - info.rcMonitor.left;
    int height = info.rcMonitor.bottom - info.rcMonitor.top;

    SetWindowLongPtrW(hwnd, GWL_STYLE, WS_POPUP | WS_VISIBLE);
    SetWindowLongPtrW(hwnd, GWL_EXSTYLE, RenderWindowTaskbarExStyle(g_engine.m_bChildMode));
    // Respect Always On Top preference — do not force TOPMOST (mirror mode used to
    // leave the window topmost while m_bAlwaysOnTop stayed false, so the toggle
    // looked stuck).
    HWND zOrder = g_engine.m_bAlwaysOnTop ? HWND_TOPMOST : HWND_NOTOPMOST;
    SetWindowPos(hwnd, zOrder, info.rcMonitor.left, info.rcMonitor.top, width, height,
                 QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED | SWP_SHOWWINDOW));

    g_engine.SetVariableBackBuffer(width, height);
    // DX12: swap chain resize is triggered by the WM_SIZE handler after SetWindowPos.

    SetThreadExecutionState(ES_DISPLAY_REQUIRED | ES_CONTINUOUS | ES_SYSTEM_REQUIRED | ES_AWAYMODE_REQUIRED);
    DragAcceptFiles(hwnd, TRUE);
    fullscreen = true;
    ForegroundUnlessQuietStartup(hwnd);
  }
  stretch = false;
}

void SetWindowFixedDimensions(HWND hwnd) {
  int windowX = 0;
  int windowY = 0;

  RECT rect;
  if (GetWindowRect(hwnd, &rect)) {
    windowX = rect.left;
    windowY = rect.top;
  }

  // Restore the window to a normal state if minimized or maximized
  ShowWindow(hwnd, QuietShow(SW_RESTORE));

  // Adjust the window size and position
  SetWindowPos(hwnd, HWND_NOTOPMOST, windowX, windowY, g_engine.m_WindowFixedWidth, g_engine.m_WindowFixedHeight, SWP_FRAMECHANGED | SWP_NOZORDER | SWP_NOACTIVATE);
}

void ResetWindow(HWND hwnd) {
  // Get the screen dimensions
  int screenWidth = GetSystemMetrics(SM_CXSCREEN);
  int screenHeight = GetSystemMetrics(SM_CYSCREEN);

  int windowWidth = screenWidth / 3;
  int windowHeight = screenHeight / 3;

  int windowX = screenWidth - windowWidth - windowWidth / 4;
  int windowY = windowHeight / 4;

  // Restore the window to a normal state if minimized or maximized
  ShowWindow(hwnd, QuietShow(SW_RESTORE));

  // Remove any transparency or click-through flags
  LONG_PTR exStyle = GetWindowLongPtr(hwnd, GWL_EXSTYLE);
  exStyle &= ~(WS_EX_LAYERED | WS_EX_TRANSPARENT); // Remove transparency and click-through
  SetWindowLongPtr(hwnd, GWL_EXSTYLE, exStyle);

  // Reset the window style to a standard overlapped window
  SetWindowLongPtrW(hwnd, GWL_STYLE, WS_OVERLAPPEDWINDOW | WS_VISIBLE);

  // Adjust the window size and position
  SetWindowPos(hwnd, HWND_NOTOPMOST, windowX, windowY, windowWidth, windowHeight, SWP_FRAMECHANGED | SWP_NOZORDER | SWP_NOACTIVATE);

  // Ensure the window is fully opaque
  SetLayeredWindowAttributes(hwnd, 0, 255, LWA_ALPHA);

  g_engine.fOpacity = 1.0f;
  g_engine.m_WindowBorderless = false;
  borderless = false;
  clickthrough = false;
  fullscreen = false;
  ForceCursorVisible();
}

static void ToggleBorderlessWindow(HWND hwnd) {
  // Not the file-scope lastRect: that one is the rect to restore to when
  // LEAVING fullscreen, and overwriting it here would make a border toggle
  // taken while fullscreen "restore" to the fullscreen size. This is just the
  // current frame, re-read on every call and used only for the SetWindowPos.
  RECT rc = { 0 };
  GetWindowRect(hwnd, &rc);
  int x = rc.left;
  int y = rc.top;
  int width = rc.right - rc.left;
  int height = rc.bottom - rc.top;

  static bool wasTransparent = false; // Track if the window was transparent before toggling

  // Check if the window currently has transparency
  BYTE currentAlpha = 255; // Default to fully opaque
  DWORD flags = 0;
  COLORREF colorKey = 0;
  if (GetLayeredWindowAttributes(hwnd, &colorKey, &currentAlpha, &flags)) {
    wasTransparent = (flags & LWA_COLORKEY) != 0; // Check if LWA_COLORKEY is set
  }

  // --- Preserve current topmost state ---
  // Determine if the window is currently topmost
  HWND hInsertAfter = HWND_NOTOPMOST;
  // WS_EX_TOPMOST is 0x00000008L
  LONG_PTR exStyle = GetWindowLongPtr(hwnd, GWL_EXSTYLE);
  if (exStyle & WS_EX_TOPMOST) {
    hInsertAfter = HWND_TOPMOST;
  }

  if (!borderless) {
    // Save the current window position and size

    // Set the window style to borderless
    SetWindowLongPtrW(hwnd, GWL_STYLE, WS_POPUP | WS_VISIBLE);

    // Reapply transparency only if it was present before
    if (wasTransparent) {
      SetLayeredWindowAttributes(hwnd, RGB(0, 0, 0), 255, LWA_COLORKEY);
    }

    SetWindowPos(hwnd, hInsertAfter, x, y, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    borderless = true;
  }
  else {
    // Restore the previous window style and position
    SetWindowLongPtrW(hwnd, GWL_STYLE, WS_OVERLAPPEDWINDOW | WS_VISIBLE);

    // Reapply transparency only if it was present before
    if (wasTransparent) {
      SetLayeredWindowAttributes(hwnd, RGB(0, 0, 0), 255, LWA_COLORKEY);
    }

    SetWindowPos(hwnd, hInsertAfter, x, y, width, height, QuietSwp(SWP_DRAWFRAME | SWP_FRAMECHANGED));
    borderless = false;
  }
  g_engine.m_WindowBorderless = borderless;
}


