static bool RectLooksLikeFullscreen(const RECT& rc, int slopPx = 8) {
  auto nearEq = [slopPx](LONG a, LONG b) {
    LONG d = a - b;
    return d <= slopPx && d >= -slopPx;
  };
  auto covers = [&](const RECT& t) {
    return nearEq(rc.left, t.left) && nearEq(rc.top, t.top) &&
           nearEq(rc.right, t.right) && nearEq(rc.bottom, t.bottom);
  };

  const int w = rc.right - rc.left;
  const int h = rc.bottom - rc.top;
  struct EnumCtx { RECT rc; int w, h, slop; bool hit; };
  EnumCtx ctx = { rc, w, h, slopPx, false };
  EnumDisplayMonitors(nullptr, nullptr,
    [](HMONITOR hMon, HDC, LPRECT, LPARAM lp) -> BOOL {
      auto* c = reinterpret_cast<EnumCtx*>(lp);
      MONITORINFO mi = { sizeof(mi) };
      if (!GetMonitorInfoW(hMon, &mi))
        return TRUE;
      auto nearEq = [c](LONG a, LONG b) {
        LONG d = a - b;
        return d <= c->slop && d >= -c->slop;
      };
      auto covers = [&](const RECT& t) {
        return nearEq(c->rc.left, t.left) && nearEq(c->rc.top, t.top) &&
               nearEq(c->rc.right, t.right) && nearEq(c->rc.bottom, t.bottom);
      };
      if (covers(mi.rcMonitor) || covers(mi.rcWork)) {
        c->hit = true;
        return FALSE;
      }
      // Saved FS rect can miss the monitor origin (mixed DPI / unaligned tops)
      // but still match that display's pixel size.
      const int mw = mi.rcMonitor.right - mi.rcMonitor.left;
      const int mh = mi.rcMonitor.bottom - mi.rcMonitor.top;
      if (nearEq(c->w, mw) && nearEq(c->h, mh)) {
        c->hit = true;
        return FALSE;
      }
      return TRUE;
    }, reinterpret_cast<LPARAM>(&ctx));
  if (ctx.hit)
    return true;

  const int vl = GetSystemMetrics(SM_XVIRTUALSCREEN);
  const int vt = GetSystemMetrics(SM_YVIRTUALSCREEN);
  const int vw = GetSystemMetrics(SM_CXVIRTUALSCREEN);
  const int vh = GetSystemMetrics(SM_CYVIRTUALSCREEN);
  RECT virt = { vl, vt, vl + vw, vt + vh };
  return covers(virt);
}

// Remember the last real windowed rect so quitting while fullscreen does not
// persist a monitor-sized frame (next launch would come back maximized).
static void PersistLastRectAsWindowedRestore() {
  const int w = lastRect.right - lastRect.left;
  const int h = lastRect.bottom - lastRect.top;
  if (w < 160 || h < 120)
    return;
  if (RectLooksLikeFullscreen(lastRect))
    return;
  g_engine.m_WindowX = lastRect.left;
  g_engine.m_WindowY = lastRect.top;
  g_engine.m_WindowWidth = w;
  g_engine.m_WindowHeight = h;
}

// Geometry check: window covers the nearest monitor (full rcMonitor or work area).
// Used to resync the sticky `fullscreen` flag when UI/mirrors resized without updating it.
static bool WindowCoversNearestMonitor(HWND hWnd, bool workAreaOnly, int slopPx = 4) {
  if (!hWnd || !IsWindow(hWnd)) return false;
  HMONITOR hMon = MonitorFromWindow(hWnd, MONITOR_DEFAULTTONEAREST);
  MONITORINFO mi = { sizeof(mi) };
  if (!hMon || !GetMonitorInfoW(hMon, &mi)) return false;
  const RECT& target = workAreaOnly ? mi.rcWork : mi.rcMonitor;
  RECT rc = {};
  if (!GetWindowRect(hWnd, &rc)) return false;
  auto nearEq = [slopPx](LONG a, LONG b) {
    LONG d = a - b;
    return d <= slopPx && d >= -slopPx;
  };
  return nearEq(rc.left, target.left) && nearEq(rc.top, target.top) &&
         nearEq(rc.right, target.right) && nearEq(rc.bottom, target.bottom);
}

static void ToggleFullScreen(HWND hwnd); // defined below

// Check if window is in any form of fullscreen (true FS covering monitor, or borderless work-area).
static bool IsAnyFullscreen(HWND hWnd) {
  // Sticky flag alone is not enough — can desync after mirrors/UI resize.
  if (fullscreen && WindowCoversNearestMonitor(hWnd, false))
    return true;
  if (WindowCoversNearestMonitor(hWnd, false)) {
    fullscreen = true; // resync
    return true;
  }
  return g_engine.IsBorderlessFullscreen(hWnd);
}

// Force primary to true monitor fullscreen (WS_POPUP covering rcMonitor).
// Geometry-only "already covers" is not enough: a windowed/overlapped frame can
// fill the portrait monitor (fs=0) and must still drop chrome and go popup FS.
static void EnsureFullScreen(HWND hwnd) {
  if (!hwnd || !IsWindow(hwnd)) return;

  const LONG_PTR style = GetWindowLongPtrW(hwnd, GWL_STYLE);
  const bool popupNoChrome = (style & WS_POPUP) &&
      !(style & (WS_CAPTION | WS_THICKFRAME | WS_SYSMENU));
  const bool covers = WindowCoversNearestMonitor(hwnd, false);
  if (fullscreen && popupNoChrome && covers)
    return;

  // Never take ToggleFullScreen's *exit* branch.
  fullscreen = false;
  ToggleFullScreen(hwnd);

  if (!(fullscreen && WindowCoversNearestMonitor(hwnd, false))) {
    fullscreen = false;
    ToggleFullScreen(hwnd);
  }
}

