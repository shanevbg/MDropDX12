// How the process was asked to show its window: WinMain's nCmdShow, which is
// STARTUPINFO.wShowWindow when the launcher set STARTF_USESHOWWINDOW.
//
// It was received and thrown away, and the first show was hardcoded to SW_SHOW
// -- which ACTIVATES. So a launcher asking for SW_SHOWNOACTIVATE got the
// foreground taken anyway, which is the one thing that request exists to
// prevent. The probe harness has always asked (see launch_mdrop) and has always
// been ignored; reported as "when mdx12test started up it stole focus for a
// second while I was typing", and a focus steal during a test does not merely
// interrupt, it lands the keystrokes in the window under test.
//
// SW_SHOWNORMAL is the fallback, which is what a process started without
// STARTF_USESHOWWINDOW receives anyway, so an ordinary launch is unchanged.
int g_iCmdShow = SW_SHOWNORMAL;

// A process launched SW_SHOWNOACTIVATE never takes the foreground by itself.
//
// Not a startup latch -- that was tried and measured wrong. Honouring nCmdShow
// at the first ShowWindow left one launch in three still stealing focus, and
// dropping the latch after EnsureFullScreen made it five in five: the
// activation that actually bites happens LATER than the window setup, once the
// message loop is running, so any "startup is over now" marker is placed
// before the thing it was meant to cover. Bisected by suppressing
// unconditionally, which held the foreground 4 launches out of 4.
//
// Permanent is also the honest reading of the request. SW_SHOWNOACTIVATE is a
// launcher saying "come up without taking the foreground", and there is no
// moment after which that stops being what it asked for. Shane's framing of
// the startup fullscreen it suppresses: "that was by design, but in testing
// it's intrusive" -- so the designed behaviour stays for a normal launch,
// which passes SW_SHOWNORMAL and is completely unaffected.
//
// Real children get this too, and want it: ChildSpawnNow launches them
// SW_SHOWNOACTIVATE precisely so enabling a display does not take the keyboard
// from whatever the user is typing into. The parent can still put a child in
// front deliberately -- RAISE_WINDOW goes through WM_MW_RAISE_WINDOW and
// SetWindowPos, not through here.
bool QuietLaunch() { return g_iCmdShow == SW_SHOWNOACTIVATE; }

// SetWindowPos flags, plus SWP_NOACTIVATE when the launch was quiet.
//
// This is the one that actually bit. SWP_SHOWWINDOW shows a window AND
// activates it unless SWP_NOACTIVATE is set, so the startup fullscreen took
// the foreground through SetWindowPos while every SetForegroundWindow in the
// file was already suppressed -- which is why suppressing those looked like it
// worked (2 launches in 6) and did not.
UINT QuietSwp(UINT flags) { return QuietLaunch() ? (flags | SWP_NOACTIVATE) : flags; }

// ShowWindow command, demoted to the non-activating equivalent when quiet.
int QuietShow(int cmd) {
  if (!QuietLaunch()) return cmd;
  if (cmd == SW_SHOW || cmd == SW_SHOWNORMAL || cmd == SW_RESTORE)
    return SW_SHOWNOACTIVATE;
  return cmd;
}

void ForegroundUnlessQuietStartup(HWND h) {
  if (QuietLaunch()) return;
  SetForegroundWindow(h);
}

