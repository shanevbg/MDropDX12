static void IdleRestoreDisplays()
{
  for (auto& out : g_engine.m_displayOutputs) {
    if (out.config.type != DisplayOutputType::Monitor) continue;
    bool found = false;
    for (const auto& s : idlePrevMonitorEnabled) {
      if (s.first == out.config.szDeviceName) {
        out.config.bEnabled = s.second;
        found = true;
        break;
      }
    }
    if (!found)
      out.config.bEnabled = false;
  }
  idlePrevMonitorEnabled.clear();
}

